#!/usr/bin/env node
/**
 * Creates `.dev.vars` for local development and end-to-end runs, if it does not
 * already exist.
 *
 * The passphrase here is a throwaway development value that lives only on this
 * machine. Alex's real passphrase is never stored in a file and never passes
 * through this script — it goes straight into `wrangler secret put`.
 *
 * An existing `.dev.vars` is left completely alone.
 */
import { existsSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const TARGET = resolve(ROOT, '.dev.vars')

export const DEV_PASSPHRASE = process.env.E2E_PASSPHRASE ?? 'pack-smart-e2e-passphrase'

if (existsSync(TARGET)) {
  console.log('.dev.vars already exists — leaving it untouched.')
  console.log('If end-to-end login fails, set E2E_PASSPHRASE to match that file.')
  process.exit(0)
}

// Must match PBKDF2_ITERATIONS in shared/crypto.ts — the Workers free plan's
// 10 ms CPU budget. tests/scripts/iteration-parity.test.ts pins them together.
const PBKDF2_ITERATIONS = 2_000

const salt = crypto.getRandomValues(new Uint8Array(16))
const keyMaterial = await crypto.subtle.importKey(
  'raw',
  new TextEncoder().encode(DEV_PASSPHRASE),
  'PBKDF2',
  false,
  ['deriveBits'],
)
const bits = await crypto.subtle.deriveBits(
  { name: 'PBKDF2', salt, iterations: PBKDF2_ITERATIONS, hash: 'SHA-256' },
  keyMaterial,
  256,
)

const hash = JSON.stringify({
  algorithm: 'pbkdf2-sha256',
  iterations: PBKDF2_ITERATIONS,
  salt: Buffer.from(salt).toString('base64url'),
  hash: Buffer.from(new Uint8Array(bits)).toString('base64url'),
})

const sessionSecret = Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString('base64url')

writeFileSync(
  TARGET,
  `# Generated by scripts/write-dev-vars.mjs — LOCAL DEVELOPMENT ONLY.\n` +
    `# Gitignored. Production secrets are set with \`wrangler secret put\`.\n` +
    `# Development passphrase: ${DEV_PASSPHRASE}\n` +
    `AUTH_PASSPHRASE_HASH=${hash}\n` +
    `SESSION_SECRET=${sessionSecret}\n`,
)

console.log(`Wrote .dev.vars with development passphrase: ${DEV_PASSPHRASE}`)
